package dev.ifair.luahud.api.core;

import dev.ifair.luahud.api.LuaParameter;
import dev.ifair.luahud.api.EventType;
import dev.ifair.luahud.api.LuaType;
import dev.ifair.luahud.api.ModelBuilder;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.AtomicMoveNotSupportedException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.*;

public final class StubGenerator {
    private StubGenerator() {}

    public static String generate(ApiRegistry registry) {
        return generate(registry, false);
    }

    /** Generates annotations using number for integer types when requested for Lua 5.2 compatibility. */
    public static String generate(ApiRegistry registry, boolean integersAsNumbers) {
        if (!registry.isFrozen()) throw new IllegalArgumentException("Registry must be frozen before generating its stub");
        ApiTypeContext context = new ApiTypeContext(registry, integersAsNumbers);
        StringBuilder out = new StringBuilder("---@meta\n-- Generated by LuaHUD. Runtime bindings and this file share one registry.\n\n");

        context.namedTypes.entrySet().stream().sorted(Map.Entry.comparingByValue()).forEach(entry -> {
            Object definition = entry.getKey(); String name = entry.getValue();
            if (definition instanceof LuaType<?> alias && alias.kind() == LuaType.Kind.ALIAS) {
                List<String> values = alias.stringValues();
                out.append("---@alias ").append(name);
                if (values.isEmpty()) {
                    out.append(' ').append(context.type(alias.elementType(), context.owners.get(alias))).append('\n');
                } else {
                    out.append('\n');
                    values.forEach(value -> out.append("---| ").append(LuaType.literal(value).luaName()).append('\n'));
                }
                out.append('\n');
                return;
            }
            if (definition instanceof ApiTypeContext.InputModel) {
                out.append("---Table schema: additional fields are accepted; no constructor is required.\n");
            }
            out.append("---@class ").append(name).append('\n');
            if (definition instanceof ModelBuilder<?> model) {
                model.fields().stream().sorted(Comparator.comparing(ModelBuilder.Field::name)).forEach(field -> field(out, field.name(), context.type(field.type(), model.providerId()), field.doc().description(), field.optional()));
            } else if (definition instanceof ApiTypeContext.InputModel input) {
                input.model().fields().stream().filter(field -> field.inputMode() != ModelBuilder.InputMode.OUTPUT_ONLY)
                        .sorted(Comparator.comparing(ModelBuilder.Field::name))
                        .forEach(field -> field(out, field.name(), context.inputFieldType(field.type(), input.model().providerId()),
                                field.doc().description(), field.inputMode() != ModelBuilder.InputMode.REQUIRED));
            } else if (definition instanceof LuaType<?> input) {
                input.inputFields().values().stream().sorted(Comparator.comparing(LuaType.InputField::name)).forEach(field -> field(out, field.name(), context.type(field.type(), context.owners.get(input)), field.doc().description(), field.optional()));
            }
            out.append('\n');
        });

        List<NamespaceInfo> namespaces = new ArrayList<>();
        collectNamespaces(registry.rootNode(), "lh", namespaces);
        namespaces.sort(Comparator.comparing(NamespaceInfo::path).reversed());
        for (NamespaceInfo info : namespaces) {
            out.append("---@class ").append(className(info.path())).append('\n');
            info.node().children().values().stream().sorted(Comparator.comparing(ApiRegistry.Node::name)).forEach(child -> {
                if (child instanceof ApiRegistry.NamespaceNode) field(out, child.name(), className(info.path() + "." + child.name()), child.doc().description(), false);
                else if (child instanceof ApiRegistry.ValueNode value) field(out, child.name(), context.type(value.type(), value.providerId()), value.doc().description(), false);
            });
            if (!info.path().equals("lh")) out.append('\n');
        }
        out.append("lh = {}\n\n");

        List<FunctionInfo> functions = new ArrayList<>();
        collectFunctions(registry.rootNode(), "lh", functions);
        functions.sort(Comparator.comparing(FunctionInfo::path));
        for (FunctionInfo info : functions) {
            ApiRegistry.FunctionNode function = info.function();
            description(out, function.doc().description());
            if (function.special() == ApiRegistry.SpecialFunction.EVENT) {
                registry.events().stream().sorted(Comparator.comparing(EventType::name)).forEach(event -> {
                    out.append("---@overload fun(event: ").append(LuaType.literal(event.name()).luaName())
                            .append(", callback: fun(");
                    if (event.hasPayload()) out.append("event: ").append(context.type(event.payloadType(), event.providerId()));
                    out.append("))\n");
                });
            }
            for (LuaParameter<?> parameter : function.parameters()) {
                out.append("---@param ").append(parameter.name());
                if (parameter.type().kind() == LuaType.Kind.OPTIONAL) out.append('?');
                out.append(' ').append(context.type(parameter.type().kind() == LuaType.Kind.OPTIONAL ? parameter.type().elementType() : parameter.type(), function.providerId()));
                appendDescription(out, parameter.doc().description());
                out.append('\n');
            }
            out.append("---@return ").append(context.type(function.returnType(), function.providerId())).append('\n');
            out.append("function ").append(info.path()).append('(')
                    .append(String.join(", ", function.parameters().stream().map(LuaParameter::name).toList()))
                    .append(") end\n\n");
        }
        return out.toString();
    }

    public static boolean writeIfChanged(Path target, String content) throws IOException {
        byte[] bytes = content.getBytes(StandardCharsets.UTF_8);
        if (Files.exists(target) && Arrays.equals(Files.readAllBytes(target), bytes)) return false;
        Files.createDirectories(target.getParent());
        Path temporary = Files.createTempFile(target.getParent(), target.getFileName().toString(), ".tmp");
        try {
            Files.write(temporary, bytes);
            try { Files.move(temporary, target, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING); }
            catch (AtomicMoveNotSupportedException ignored) { Files.move(temporary, target, StandardCopyOption.REPLACE_EXISTING); }
        } finally { Files.deleteIfExists(temporary); }
        return true;
    }

    private static void field(StringBuilder out, String name, String type, String description, boolean optional) {
        out.append("---@field ").append(name); if (optional) out.append('?'); out.append(' ').append(type); appendDescription(out, description); out.append('\n');
    }
    private static void description(StringBuilder out, String description) { if (!description.isBlank()) for (String line : description.replace("\r", "").split("\n")) out.append("---").append(line.replace("---@", "@" )).append('\n'); }
    private static void appendDescription(StringBuilder out, String description) { if (!description.isBlank()) out.append(' ').append(description.replace("\r", " ").replace("\n", " ").replace("---@", "@")); }
    private static String className(String path) { return path.equals("lh") ? "API" : "LuaHUD_" + path.substring(3).replace('.', '_'); }
    private static void collectNamespaces(ApiRegistry.NamespaceNode node, String path, List<NamespaceInfo> result) { result.add(new NamespaceInfo(path, node)); for (ApiRegistry.Node child : node.children().values()) if (child instanceof ApiRegistry.NamespaceNode table) collectNamespaces(table, path + "." + child.name(), result); }
    private static void collectFunctions(ApiRegistry.NamespaceNode node, String path, List<FunctionInfo> result) { for (ApiRegistry.Node child : node.children().values()) { if (child instanceof ApiRegistry.NamespaceNode table) collectFunctions(table, path + "." + child.name(), result); else if (child instanceof ApiRegistry.FunctionNode function) result.add(new FunctionInfo(path + "." + child.name(), function)); } }

    private record NamespaceInfo(String path, ApiRegistry.NamespaceNode node) {}
    private record FunctionInfo(String path, ApiRegistry.FunctionNode function) {}

}
